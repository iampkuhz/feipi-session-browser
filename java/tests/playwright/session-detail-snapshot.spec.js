const { test, expect } = require('@playwright/test');

test('导入后的首次续读等待初始快照，再定位执行轮次和首问', async ({ page, request, baseURL }) => {
  const firstQuestion = 'synthetic first question for snapshot continuation';
  const rows = [
    { type: 'session_meta', payload: { id: '11111111-1111-4111-8111-111111111191', cwd: '/synthetic' } },
    { type: 'turn_context', payload: { model: 'synthetic-model' } },
    { type: 'response_item', payload: { type: 'message', role: 'user', content: [{ type: 'input_text', text: firstQuestion }] } },
    { type: 'response_item', payload: { type: 'message', role: 'assistant', content: [{ type: 'output_text', text: 'synthetic answer' }] } },
  ];
  const headers = { Origin: new URL(baseURL).origin };
  const upload = await request.post('/api/imports', { headers, multipart: {
    source: 'codex', file: { name: 'synthetic-snapshot.jsonl', mimeType: 'application/x-ndjson', buffer: Buffer.from(rows.map(JSON.stringify).join('\n') + '\n') },
  } });
  expect(upload.status(), await upload.text()).toBe(201);
  const { import_id: id } = await upload.json();
  let releaseMetadata;
  const metadataGate = new Promise(resolve => { releaseMetadata = resolve; });
  try {
    await page.route(`**/api/imports/${id}/meta`, async route => {
      await metadataGate;
      await route.continue();
    });
    const oldIndexReads = [];
    page.on('request', req => {
      if (new URL(req.url()).pathname === `/api/imports/${id}/payloads`) oldIndexReads.push(req.url());
    });
    await page.addInitScript(() => {
      const fetchOriginal = window.fetch;
      window.roundReads = [];
      window.fetch = (url, options) => {
        if (String(url).endsWith('/round/1')) window.roundReads.push(document.body.getAttribute('data-index-generation'));
        return fetchOriginal(url, options);
      };
    });
    await page.goto(`/imports/${id}?round=1&tab=payload`);
    await expect(page.locator('body')).toHaveAttribute('data-session-api-meta-state', 'loading');
    expect(await page.evaluate(() => window.roundReads)).toEqual([]);
    releaseMetadata();
    await expect(page.locator('#round-1-detail')).toBeVisible();
    expect(await page.evaluate(() => window.roundReads)).toEqual(['legacy']);
    expect(oldIndexReads).toEqual([]);
    await page.getByRole('button', { name: '查看首问', exact: true }).click();
    await expect(page.locator('dialog[open]')).toContainText(firstQuestion);
  } finally {
    releaseMetadata();
    expect((await request.delete(`/api/imports/${id}`, { headers })).status()).toBe(204);
  }
});

test('real server rejects a stale stamp and refresh restores the round after generation change', async ({ page }) => {
  const url = '/sessions/claude_code/hifi-viz-session-001';
  const header = 'x-session-index-generation';
  await page.goto(url);
  const body = page.locator('body');
  await expect(body).toHaveAttribute('data-session-api-hydrated', 'true');
  const stamp = await body.getAttribute('data-index-generation');
  expect(stamp).toBeTruthy();

  // The response is generated by the production guard, not a mocked 409.
  const roundApi = '**/api/sessions/claude_code/hifi-viz-session-001/round/1';
  let conflictBody;
  await page.route(roundApi, async route => {
    const headers = await route.request().allHeaders();
    expect(headers[header]).toBe(stamp);
    const response = await route.fetch({ headers: { ...headers, [header]: stamp + '-stale' } });
    conflictBody = await response.json();
    await route.fulfill({ response });
  });
  const round = page.locator('[data-trace-round-row][data-round="1"]');
  const pendingConflict = page.waitForResponse(response => response.url().endsWith('/round/1'));
  await round.locator('[data-action="toggle-round"]').click();
  const conflict = await pendingConflict;
  expect(conflict.status()).toBe(409);
  expect(conflictBody).toMatchObject({ error: 'index_generation_changed' });
  await expect(page.locator('#round-1-detail')).toHaveCount(0);
  await page.unroute(roundApi);

  await page.getByRole('button', { name: 'Refresh page', exact: true }).click();
  await expect(page).toHaveURL(/round=1/);
  await expect(page.locator('#round-1-detail')).toBeVisible();
  await expect(page.locator('[data-loading-for="1"]')).toHaveCount(0);
});

for (const intent of ['round', 'first-question', 'tool-result', 'tool-relocated', 'tool-missing', 'second-conflict']) {
  test(`generation recovery reloads once and restores ${intent} from the new view`, async ({ page }) => {
    const session = '/sessions/claude_code/hifi-viz-session-001';
    const api = '/api' + session;
    const header = 'x-session-index-generation';
    const old = 'synthetic-old-publication';
    const toolIntent = intent.startsWith('tool-');
    let documents = 0;
    let published;
    let conflicts = 0;
    await page.route(`**${session}*`, async route => {
      if (!route.request().isNavigationRequest()) return route.continue();
      documents++;
      const response = await route.fetch();
      published = response.headers()[header];
      if (documents !== 1) return route.fulfill({ response });
      const body = (await response.text()).replace(`data-index-generation="${published}"`, `data-index-generation="${old}"`);
      await route.fulfill({ response, body });
    });
    await page.route(`**${api}/**`, async route => {
      const pathname = new URL(route.request().url()).pathname;
      const headers = await route.request().allHeaders();
      const matches = intent === 'round' ? pathname === api + '/round/1'
        : toolIntent ? decodeURIComponent(pathname).includes('/payload/tool:result:')
        : pathname.startsWith(api + '/payload/');
      if (matches && documents === 1) {
        expect(headers[header]).toBe(old);
        const response = await route.fetch();
        expect(response.status()).toBe(409);
        expect(response.headers()[header]).toBe(published);
        conflicts++;
        return route.fulfill({ response });
      }
      if (matches && intent === 'second-conflict' && documents === 2) {
        const response = await route.fetch({ headers: { ...headers, [header]: old } });
        expect(response.status()).toBe(409);
        conflicts++;
        return route.fulfill({ response, headers: { ...response.headers(), [header]: 'synthetic-third-publication' } });
      }
      // New publication still owns the tool, but a newly discovered boundary moved it to round 1.
      if (intent === 'tool-relocated' && documents === 2 && new URL(route.request().url()).searchParams.has('target')) {
        if (pathname === api + '/execution') {
          const response = await route.fetch();
          const json = await response.json();
          return route.fulfill({ response, json: { ...json, items: json.items.map(item => ({ ...item, group: { ...item.group, round: 1 } })) } });
        }
        if (pathname === api + '/round/1') {
          const response = await route.fetch({ url: route.request().url().replace('/round/1?', '/round/2?') });
          return route.fulfill({ response });
        }
        if (pathname === api + '/round/2') return route.fulfill({ status: 404, json: { error: 'target_not_in_round' } });
      }
      if (intent === 'tool-missing' && documents === 2 && pathname === api + '/round/2') {
        const response = await route.fetch();
        const json = await response.json();
        await route.fulfill({ response, json: { ...json, round: { ...json.round, tools: [], toolCallIds: [] } } });
        return;
      }
      if (documents !== 1) return route.continue();
      const response = await route.fetch({ headers: { ...headers, [header]: published } });
      await route.fulfill({ response, headers: { ...response.headers(), [header]: old } });
    });

    await page.goto(session);
    await expect(page.locator('body')).toHaveAttribute('data-session-api-hydrated', 'true');
    const roundId = toolIntent ? 2 : 1;
    const round = page.locator(`[data-trace-round-row][data-round="${roundId}"]`);
    const detail = page.locator(`#round-${roundId}-detail`);
    const resultPair = detail.locator('[data-tool-payload-pair][data-result-observed="true"]').first();
    const modal = page.locator('dialog[open]');
    if (intent === 'round' || toolIntent) {
      await round.locator('[data-action="toggle-round"]').click();
      if (toolIntent) await resultPair.locator('summary').click();
    } else {
      await page.locator('[data-session-first-question] [data-action="open-payload"]').click();
    }

    await expect(page.locator('body')).toHaveAttribute('data-index-generation', published);
    if (intent === 'round') await expect(detail).toBeVisible();
    if (intent === 'tool-result') await expect(resultPair.locator('pre').last()).not.toContainText(/正在加载|Index changed|内容未记录/);
    if (intent === 'tool-relocated') {
      await expect(page).toHaveURL(/round=1/);
      await expect(page.locator('#round-1-detail [data-tool-payload-pair][open] pre').last()).not.toContainText(/正在加载|Index changed|内容未记录/);
    }
    if (intent === 'tool-missing') {
      await expect(page.locator('[data-reading-navigation-error][role="alert"]')).toContainText('无法定位执行记录');
      await expect(resultPair.locator('pre')).toHaveCount(0);
    }
    if (intent === 'first-question') await expect(modal).toContainText('create the implementation plan.');
    if (intent === 'second-conflict') {
      await expect(modal.getByRole('button', { name: 'Refresh page', exact: true })).toBeVisible();
      await expect(modal).not.toContainText('create the implementation plan.');
    }
    expect(conflicts).toBe(intent === 'second-conflict' ? 2 : 1);
    expect(documents).toBe(2);
  });
}
